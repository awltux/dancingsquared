// A REPLAY'S EVERY CALL ANIMATES — the picture the `Play` button promises.
//
// REPORTED: "when I press play for the completed Today's Daily, the first two calls don't animate, they just jump
// between arrangements, but the last two calls do animate."
//
// THE CAUSE WAS IN THE ENGINE, and this probe is where it is visible: `evaluateSequence` read a step's raw text
// with `splitSelection`, which cannot know whether the catalogue publishes the whole string as one title.
// `"Centers Cast Off Third Quarters"` — that Daily's own first TWO calls — IS such a title (a `<tam>` in
// `ms/cast.xml`), so `applyToBoard` danced it whole while the animation danced `Cast Off Three Quarters` for
// `Centers`, a step whose own apply is ILLEGAL on that board. `animateParallelBoard` returns the board unchanged
// in that case, so the step stood still for its whole 4.5 beats and snapped on the last frame. MEASURED at 60 fps
// on the 2026-10-24 Daily (level 1, seed 2036023644): the four calls drew 1, 1, 270 and 361 distinct boards —
// and 271, 270, 270, 361 after the engine read the title as the applicator does.
//
// THE JUDGE IS THE FRAME, NOT THE ENDPOINT, and that distinction is the whole check: a step that stands still for
// its duration and snaps on its last frame draws the correct FINAL board, so an endpoint check passes for as long
// as the defect exists. `scoped-coded-animation-probe`'s note in `engine/test/suite.mjs` records the same metric
// being repaired for the same reason.
//
// THE SAMPLE IS THE GAME'S OWN PUZZLES, generated by the same code the Daily is published from, so a corpus
// retitle or a generator change re-measures this rather than stepping around a hard-coded line.
import { generatePuzzle } from '../src/puzzle/generator.ts';
import { generatorConfigFor } from '../src/puzzle/config.ts';
import { levelSpec, dailySpec } from '../src/puzzle/levels.ts';
import { MAIN_POOL, poolFor } from '../src/puzzle/pool.ts';
import { dailyEntry } from '../src/puzzle/daily.ts';
import { applierFor } from '../src/data/corpus-node.ts';

let failures = 0;
const check = (cond, msg) => {
  console.log(cond ? '  ok   ' + msg : '  FAIL ' + msg);
  if (!cond) failures++;
};

/** The Dailies the probe walks: consecutive UTC days at level 1, each a different puzzle. */
const DAYS = ['2026-10-24', '2026-10-25', '2026-10-26', '2026-10-27'];
const FRAME = 1 / 60;

const LEVEL = levelSpec(1);
const spec = dailySpec(LEVEL);
const { applier } = applierFor(poolFor(spec, MAIN_POOL), spec.poolSize);

/** How many distinct boards the stage would draw inside one call, at 60 fps. */
function distinctBoards(motion, from, to) {
  const seen = [];
  for (let beat = from; beat <= to; beat += FRAME) {
    const frame = motion.at(beat);
    const same = seen.some((b) => b.dancers.length === frame.dancers.length && b.dancers.every((d, i) => {
      const e = frame.dancers[i];
      return !!e && d.id === e.id && Math.abs(d.x - e.x) < 1e-9 && Math.abs(d.y - e.y) < 1e-9;
    }));
    if (!same) seen.push(frame);
  }
  return seen.length;
}

let measured = 0;
let still = 0;
for (const day of DAYS) {
  const entry = dailyEntry(LEVEL, MAIN_POOL.version, day);
  const built = generatePuzzle(generatorConfigFor(MAIN_POOL.version, spec, 'daily'), entry.seed, spec, applier);
  if (!built.ok) {
    // A DAY THAT DOES NOT GENERATE IS REPORTED, NOT SKIPPED: an empty sample that passes is the failure mode
    // `AGENTS.md` 11.2 #2 names.
    check(false, `the ${day} Daily generates (${built.reason})`);
    continue;
  }
  const puzzle = built.puzzle;
  const calls = puzzle.solution;
  const per = [];
  let board = puzzle.start;
  for (const call of calls) {
    per.push(applier.motion([call], board).beats);
    board = applier.apply(board, call);
  }
  const whole = applier.motion(calls, puzzle.start);
  console.log(`== ${day}: ${calls.length} call(s), ${whole.beats} beats — ${calls.join(' → ')} ==`);
  let ends = 0;
  for (let k = 0; k < calls.length; k++) {
    const from = ends;
    ends += per[k];
    if (per[k] <= 0) {
      // A ZERO-BEAT CALL HAS NOTHING TO DRAW, and saying so is not a pass: it is excluded and counted.
      console.log(`  --   ${calls[k]}: charged 0 beats, nothing to draw (excluded)`);
      continue;
    }
    const frames = distinctBoards(whole, from, ends);
    measured++;
    const ok = frames > 1;
    if (!ok) still++;
    check(ok, `  ${calls[k]} draws ${frames} distinct board(s) over ${per[k]} beats`);
  }
}

// THE DENOMINATOR IS THE CLAIM, and a sample of zero calls would otherwise pass.
check(measured > 0, `the sample is not empty (${measured} call(s) with beats, over ${DAYS.length} Daily/ies)`);
check(still === 0, `every one of them animates (${still} stood still)`);

console.log(`\n${failures === 0 ? 'ALL CHECKS PASSED' : `${failures} CHECK(S) FAILED`}`);
process.exit(failures === 0 ? 0 : 1);
