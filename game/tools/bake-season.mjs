// The offline season, BAKED: generate each fixture entry's puzzle once, here, and write it as data.
//
//   node game/tools/bake-season.mjs
//
// WHY THIS EXISTS AT ALL. The client used to derive a drill from a seed, and the last two commits moved generation
// to the serving side (DESIGN.md §9). The fixture season is the one path with no server to ask, so something has to
// carry its boards — and the answer is a checked-in file rather than a call, because "no puzzle is generated on the
// client" is a property a bundle can be measured for (`game/test/client-generation-probe.mjs` walks the app's
// import graph). Baking keeps the promise without deleting the mode.
//
// THIS TOOL IS NOT IN A GATE AND MUST NOT BE RUN BY ONE. Its output is checked in and `game/test/schedule-fixture-probe.mjs`
// re-generates every entry and compares, which is the gate: a corpus, pool or generator change that makes a baked
// puzzle disagree with what the generator now produces turns that probe red. The tool is for when the probe says
// so (or when the fixture's entries change), and running it is a deliberate act with a diff to read.
//
// THE OUTPUT IS ONE PUZZLE PER FIXTURE ENTRY, in the fixture's order, with no key: the entry's position IS the key,
// and a map keyed by seed would quietly give two levels' puzzles the same key, because the fixture reuses seeds
// 1..4 at each level.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generatePuzzle } from '../src/puzzle/generator.ts';
import { generatorConfigFor } from '../src/puzzle/config.ts';
import { levelSpec } from '../src/puzzle/levels.ts';
import { poolFor } from '../src/puzzle/pool.ts';
import { MAIN_POOL } from '../src/puzzle/pool.ts';
import { LOCAL_SCHEDULE, FIXTURE_POOL_VERSION } from '../src/game/schedule-fixture.ts';
import { applierFor } from '../src/data/corpus-node.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'src', 'game', 'season-data.ts');

/**
 * ONE APPLIER PER LEVEL, built once.
 *
 * Constructing a sequencer over a level's calls is the expensive half of generating, and the fixture reuses each
 * level many times — level 1 a hundred times. MEASURED while this was built inside the loop: the 108-puzzle bake
 * took **405 s**, against **35 s** with the applier hoisted, and the difference is entirely registration. The probe
 * that re-generates this file already caches the same way (`test/schedule-fixture-probe.mjs`), so this also keeps
 * the two runs of the same generation comparable.
 */
const runtimes = new Map();
function runtimeFor(levelIndex) {
  let entry = runtimes.get(levelIndex);
  if (!entry) {
    const level = levelSpec(levelIndex);
    if (!level) throw new Error(`fixture entry names level ${levelIndex}, which is not a level`);
    entry = { level, ...applierFor(poolFor(level, MAIN_POOL), level.poolSize) };
    runtimes.set(levelIndex, entry);
  }
  return entry;
}

const puzzles = [];
for (const [position, entry] of LOCAL_SCHEDULE.entries()) {
  const { level, applier } = runtimeFor(entry.levelIndex);
  const generated = generatePuzzle(generatorConfigFor(FIXTURE_POOL_VERSION, level), entry.seed, level, applier);
  if (!generated.ok) throw new Error(`fixture entry ${position} (level ${entry.levelIndex}, seed ${entry.seed}) does not generate: ${generated.reason}`);
  puzzles.push(generated.puzzle);
  console.log(`entry ${position}: level ${entry.levelIndex}, seed ${entry.seed}, ${generated.puzzle.steps.length} step(s)`);
}

// JSON WITH A CAST, rather than a hand-formatted literal: the file is data, and `as unknown as Puzzle[]` is the one
// place a wrong shape could hide. It is covered by the probe that re-generates and compares — which is a stronger
// check than a typed literal would give, because it compares against the generator rather than against the type.
const header = `// THE OFFLINE SEASON'S PUZZLES, GENERATED BY \`game/tools/bake-season.mjs\` AND CHECKED IN.
//
// DO NOT EDIT BY HAND. Every puzzle here is exactly what \`generatePuzzle\` produces for the fixture entry at the
// same POSITION (\`LOCAL_SCHEDULE\`, \`game/src/game/schedule-fixture.ts\`); \`game/test/schedule-fixture-probe.mjs\`
// re-generates each one and compares, so an edit that disagrees with the generator turns that probe red.
//
// WHY DATA AND NOT A CALL: the client generates no puzzle at all (DESIGN.md §9), and the fixture season is the one
// path with no server to ask. \`game/test/client-generation-probe.mjs\` pins that by walking the app's import graph.
//
// POOL VERSION ${FIXTURE_POOL_VERSION} — a pool change invalidates every board below, and the probe says so rather
// than the app serving a puzzle from a call set that no longer exists.
import type { Puzzle } from '../puzzle/types.ts';

export const SEASON_POOL_VERSION = ${JSON.stringify(FIXTURE_POOL_VERSION)};

export const SEASON_PUZZLES = ${JSON.stringify(puzzles, null, 0)} as unknown as readonly Puzzle[];
`;
if (!header.includes('SEASON_PUZZLES')) throw new Error('the generated file would be empty; refusing to write');
fs.writeFileSync(OUT, header, 'utf8');
const bytes = fs.statSync(OUT).size;
console.log(`\nwrote ${path.relative(process.cwd(), OUT)}: ${puzzles.length} puzzle(s), ${(bytes / 1024).toFixed(0)} KB`);
