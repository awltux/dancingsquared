// Regenerate `src/puzzle/calls-data.ts` from the corpus.
//
//   node game/tools/build-pool.mjs            write the file
//   node game/tools/build-pool.mjs --check    fail if the file on disk is not what this would write
//
// WHY THERE IS A `--check`. `calls-data.ts` is generated, and a generated artefact with no gate goes
// stale silently (AGENTS.md §8 trap 9). MEASURED: `134ff33` renamed 43 `title` attributes under
// `poc/src/assets/ms/circle.xml` — `Circle Left - Stop at Home` -> `Circle Left Home` — and nothing
// regenerated the pool, so the pool kept naming a title no tam declares. Two probes went red with a
// reason that points at the corpus rather than at the stale file ("every one of the level's 15 titles
// registered with the engine (14)"). The game's probe runner now runs this check FIRST, the way it runs
// `sync-corpus.mjs --check`, so the same edit fails in the place that names the cause.
//
// WHERE THE ORDER COMES FROM, and why it is not from `calls.xml`. The obvious source would be that
// file, and it does not work: MEASURED, `poc/src/assets/src/calls.xml` carries 690 entries and NOT ONE
// of them links `ms/…` (they are `a1`, `a2`, `b1`, `b2`, `c1`, `c2`, `c3a`, `c3b` and `ssd`), because
// the Mainstream programme is the base the index does not link. So the corpus offers no provider order
// for Mainstream, and the order here is `poc/src/assets/ms` sorted by basename — the file order the
// app's own catalogue walk uses (`poc/src/data.ts` sorts the globbed paths the same way).
//
// THAT IS A STARTING ORDER, NOT A TEACHING ORDER. DESIGN.md 5 wants the pool ordered the way a class
// meets the calls, which is a curatorial act this script cannot perform and which §15 lists as an open
// question. The header it writes says so, so nobody mistakes this for the curated list.
//
// Titles come from `callMeta`, which is the same registry `poc/src/data.ts` builds its catalogue from,
// and a file that yields several titles contributes all of them. Registration in the game is by TITLE
// (AGENTS.md §8 trap 7: a position into an authored list is not an identity).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DOMParser } from '@xmldom/xmldom';
import { setParser, callMeta } from 'dancing-squared-engine';
setParser(DOMParser);

const here = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(here, '..', '..');
const MS_DIR = path.join(REPO, 'poc', 'src', 'assets', 'ms');
const OUT = path.join(here, '..', 'src', 'puzzle', 'calls-data.ts');
const CHECK = process.argv.includes('--check');

/** The pool version. Bump when the ORDER or the membership changes: a puzzle is only meaningful
 * against one pool version (DESIGN.md 7), so this is part of what a leaderboard entry means. */
const POOL_VERSION = 'ms-2';

const files = fs.readdirSync(MS_DIR).filter((f) => f.endsWith('.xml')).sort();
const titles = [];
const failures = [];
for (const f of files) {
  const xml = fs.readFileSync(path.join(MS_DIR, f), 'utf8');
  let meta;
  try {
    meta = callMeta(xml);
  } catch (e) {
    failures.push({ file: f, reason: e instanceof Error ? e.message : String(e) });
    continue;
  }
  // A file with no call title is a moves/rule file rather than a call, which `engine/test/mainstream.mjs`
  // skips the same way.
  if (meta?.title) titles.push(meta.title);
}
// THE ORDER IS DETERMINISTIC, and the two steps are separate facts:
//   * the FILES are walked in basename order, so which title each file contributes is stable;
//   * the TITLES are then sorted explicitly, so the published order cannot depend on the filesystem's
//     case sensitivity or on `Intl` collation defaults drifting between machines. That matters more
//     than it looks: the pool order IS the ladder, so a re-sort renumbers every level's pool.
const collate = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const ordered = [...new Set(titles)].sort(collate);
if (ordered.length !== new Set(ordered).size) throw new Error('build-pool: the pool has duplicates after de-duplication');
const dupes = titles.filter((t, i) => titles.indexOf(t) !== i);
if (dupes.length) failures.push({ file: '(titles)', reason: `${new Set(dupes).size} title(s) appear in more than one file: ${[...new Set(dupes)].slice(0, 6).join(', ')}` });

const body = `// GENERATED by \`node game/tools/build-pool.mjs\` — do not edit by hand.
//
// The Mainstream call pool, in the order the game treats as its teaching sequence. Regenerate with
// that script; it reads \`poc/src/assets/ms/*.xml\` and takes each file's call title(s) from
// \`callMeta\`.
//
// WHAT THIS ORDER IS NOT: it is NOT a curated teaching order. The corpus offers none for Mainstream —
// \`poc/src/assets/src/calls.xml\` carries no \`ms/\` link at all (measured: 690 entries, none of them
// ms) — so the order is the asset directory's own, sorted by basename, which is the same walk
// \`poc/src/data.ts\` performs. DESIGN.md 5 wants the calls ordered the way a class meets them, and
// that is §15's open question 9: a curatorial act, not something this script can derive. Replacing
// this list with a curated one is a data edit plus a \`POOL_VERSION\` bump.
//
// A title here is an IDENTITY, not a position: registration in the game is by title, so re-sorting
// this array without bumping \`POOL_VERSION\` would silently renumber every level's pool.
export const POOL_VERSION = ${JSON.stringify(POOL_VERSION)};

export const CALLS_IN_ORDER: readonly string[] = [
${ordered.map((t) => `  ${JSON.stringify(t)},`).join('\n')}
];
`;

if (CHECK) {
  // THE COMPARISON NORMALISES LINE ENDINGS. The host global `core.autocrlf` is true, so a file restored
  // by `git checkout` comes back with CRLF and a literal comparison would report drift on a file that is
  // byte-identical to this script's output apart from the endings (AGENTS.md §8 trap 2).
  const onDisk = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (onDisk === body) {
    console.log(`build-pool: ${path.relative(REPO, OUT)} is current (${ordered.length} titles, ${POOL_VERSION})`);
  } else {
    const a = onDisk.split('\n');
    const b = body.split('\n');
    const at = a.findIndex((l, i) => l !== b[i]);
    console.error(`build-pool: ${path.relative(REPO, OUT)} is NOT what this script writes.`);
    console.error(`  first difference at line ${at + 1}:`);
    console.error(`    on disk: ${JSON.stringify(a[at] ?? '(nothing)')}`);
    console.error(`    wanted : ${JSON.stringify(b[at] ?? '(nothing)')}`);
    console.error('  run `node game/tools/build-pool.mjs` and commit the result.');
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, body, 'utf8');
  console.log(`build-pool: wrote ${ordered.length} titles to ${path.relative(REPO, OUT)}`);
  console.log(`  first 12: ${ordered.slice(0, 12).join(' | ')}`);
}
if (failures.length) {
  console.log(`  ${failures.length} file(s) contributed nothing or were refused:`);
  for (const f of failures.slice(0, 10)) console.log(`    ${f.file}: ${f.reason}`);
}
